/**
 * Calculates deadline status & formatted text
 */
export function getDeadlineInfo(deadlineStr) {
  if (!deadlineStr) {
    return {
      status: 'normal',
      text: 'Recruitments start soon!',
      isExpired: false,
      daysLeft: 99,
      isSoon: true,
    };
  }

  const deadlineDate = new Date(deadlineStr);
  const now = new Date();
  const diffMs = deadlineDate - now;

  if (diffMs <= 0) {
    return { status: 'expired', text: 'Closed', isExpired: true, daysLeft: -1 };
  }

  const diffHours = Math.floor(diffMs / (1000 * 60 * 60));
  const diffDays = Math.floor(diffHours / 24);

  if (diffHours < 24) {
    return {
      status: 'urgent',
      text: `Closing Today (${diffHours}h left)`,
      isExpired: false,
      daysLeft: 0,
      hoursLeft: diffHours,
    };
  }

  if (diffDays <= 3) {
    return {
      status: 'urgent',
      text: `Closing in ${diffDays} day${diffDays > 1 ? 's' : ''}`,
      isExpired: false,
      daysLeft: diffDays,
    };
  }

  return {
    status: 'normal',
    text: `${diffDays} days left`,
    isExpired: false,
    daysLeft: diffDays,
  };
}
